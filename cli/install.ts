import { spawnSync } from "node:child_process";
import { chmodSync, cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { delimiter, join, relative, resolve } from "node:path";
import { homedir } from "node:os";

import { CliError } from "./store";

/**
 * Where an `npx github:AustineA/framecraft install` puts the app.
 *
 * It cannot stay in npm's cache: rendering builds this Next.js app, and
 * Turbopack cannot build an app that lives inside `node_modules`. So the
 * source is copied somewhere stable and installed there.
 */
export const INSTALL_DIR = join(homedir(), ".framecraft");

const npm = process.platform === "win32" ? "npm.cmd" : "npm";

// Runs through a shell so version-manager shims (mise, nvm, volta) resolve —
// npx does not always leave a directly spawnable `npm` on PATH.
const npmSpawn = (args: string[], options: Parameters<typeof spawnSync>[2]) =>
  spawnSync(npm, args, { ...options, shell: process.platform !== "win32" });

/** The package root, whether running from source or from `dist/`. */
function packageRoot(): string {
  let dir = __dirname;
  for (let up = 0; up < 6; up += 1) {
    if (existsSync(join(dir, "package.json")) && existsSync(join(dir, "next.config.ts"))) {
      return dir;
    }
    dir = resolve(dir, "..");
  }
  throw new CliError("Could not locate the Framecraft package.");
}

function run(args: string[], cwd: string, label: string): void {
  const result = npmSpawn(args, { cwd, stdio: "inherit" });
  if (result.error) throw new CliError(`${label} could not start: ${result.error.message}`);
  if (result.status !== 0) throw new CliError(`${label} failed.`);
}

/**
 * Where `framecraft` lives on the PATH.
 *
 * Asks npm for its global bin rather than trusting `command -v`: while npx
 * is running, its own `.bin` shadows the global one and would be reported
 * instead of the install we just made.
 */
function linkedPath(): string | undefined {
  for (const dir of BIN_DIRS) {
    const shim = join(dir, "framecraft");
    if (existsSync(shim)) return shim;
  }

  const prefix = npmSpawn(["prefix", "-g"], { encoding: "utf8" });
  const dir = String(prefix.stdout ?? "").trim();
  if (dir) {
    const candidate = join(dir, "bin", "framecraft");
    if (existsSync(candidate)) return candidate;
  }

  const found = spawnSync(
    process.platform === "win32" ? "where" : "command",
    process.platform === "win32" ? ["framecraft"] : ["-v", "framecraft"],
    { encoding: "utf8", shell: process.platform !== "win32" },
  );
  return found.stdout?.trim().split("\n")[0] || undefined;
}

/** Directories to install the command into, best first. */
const BIN_DIRS = [join(homedir(), ".local", "bin"), join(homedir(), "bin")];

/**
 * Picks where the command goes.
 *
 * Prefers a directory already on PATH, so the command is found no matter
 * which Node is active — unlike an npm global prefix, which belongs to one
 * Node version and vanishes when you switch.
 */
function chooseBinDir(): { dir: string; onPath: boolean } {
  const entries = (process.env.PATH ?? "").split(delimiter).filter(Boolean);
  const onPath = BIN_DIRS.find((dir) => entries.includes(dir));
  if (onPath) return { dir: onPath, onPath: true };
  return { dir: BIN_DIRS[0], onPath: false };
}

/**
 * Writes a launcher that runs the CLI with a known-good Node.
 *
 * The Node that performed the install is pinned, with whatever is on PATH as
 * a fallback if that install is later removed. This is what frees the
 * command from the active Node version.
 */
function writeShim(dir: string, entry: string): string {
  mkdirSync(dir, { recursive: true });
  const shim = join(dir, "framecraft");

  writeFileSync(
    shim,
    [
      "#!/bin/sh",
      "# Generated by `framecraft install`. Safe to delete.",
      `NODE="${process.execPath}"`,
      '[ -x "$NODE" ] || NODE="$(command -v node)"',
      '[ -n "$NODE" ] || { echo "framecraft: Node.js not found" >&2; exit 1; }',
      `exec "$NODE" "${entry}" "$@"`,
      "",
    ].join("\n"),
    "utf8",
  );
  chmodSync(shim, 0o755);
  return shim;
}

export type InstallResult = {
  root: string;
  bin: string;
  copied: boolean;
  onPath: boolean;
};

/**
 * Links `framecraft` onto the PATH.
 *
 * From a clone it links that clone in place, so edits take effect after
 * `npm run build:cli`. From npx — where the source sits in a cache npm will
 * eventually delete — it is copied to `~/.framecraft` first.
 */
export function install(): InstallResult {
  const source = packageRoot();
  const fromCache = source.split(/[\\/]/).includes("node_modules");
  const root = fromCache ? INSTALL_DIR : source;

  if (fromCache) {
    if (existsSync(INSTALL_DIR)) rmSync(INSTALL_DIR, { recursive: true, force: true });
    // Compare the path *below* the source: the npx cache directory itself
    // sits under node_modules, so an absolute test would reject everything.
    cpSync(source, INSTALL_DIR, {
      recursive: true,
      filter: (path) =>
        !relative(source, path).split(/[\\/]/).includes("node_modules"),
    });
    run(["install"], INSTALL_DIR, "npm install");
  } else if (!existsSync(join(root, "node_modules"))) {
    run(["install"], root, "npm install");
  }

  run(["run", "build:cli"], root, "Compiling the CLI");

  const entry = join(root, "dist", "cli", "cli", "index.js");
  if (process.platform === "win32") {
    // No equivalent user bin directory is reliably on PATH, so Windows keeps
    // the npm global install, with its one-Node-version caveat.
    run(["link"], root, "npm link");
    const bin = linkedPath();
    if (!bin) throw new CliError("Linked, but framecraft is not on your PATH.");
    return { root, bin, copied: fromCache, onPath: true };
  }

  const { dir, onPath } = chooseBinDir();
  return { root, bin: writeShim(dir, entry), copied: fromCache, onPath };
}

export type UninstallResult = { unlinked: boolean; removed: string | undefined };

export function uninstall(): UninstallResult {
  // Remove the shim, and any npm global link from an older install.
  let unlinked = false;
  for (const dir of BIN_DIRS) {
    const shim = join(dir, "framecraft");
    if (existsSync(shim)) {
      rmSync(shim, { force: true });
      unlinked = true;
    }
  }
  if (npmSpawn(["unlink", "-g", "framecraft"], { stdio: "ignore" }).status === 0) {
    unlinked = true;
  }

  // Only remove the copy this tool made; a clone is the user's own.
  let removed: string | undefined;
  if (existsSync(INSTALL_DIR)) {
    rmSync(INSTALL_DIR, { recursive: true, force: true });
    removed = INSTALL_DIR;
  }
  return { unlinked, removed };
}

export type StatusResult = {
  installed: boolean;
  bin: string | undefined;
  root: string;
  managed: boolean;
  node: string;
};

/**
 * Where the command is installed from.
 *
 * The app root is always known — this code is running from it. The linked
 * binary is looked up in the *active* Node's global prefix, so a version
 * manager pointing at another Node reports it as unlinked there, which is
 * exactly what is happening.
 */
export function status(): StatusResult {
  const root = packageRoot();
  return {
    installed: Boolean(linkedPath()),
    bin: linkedPath(),
    root,
    managed: root === INSTALL_DIR,
    node: process.version,
  };
}
